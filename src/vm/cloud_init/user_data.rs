    #[test]
    fn the_selected_ssh_user_gets_the_only_authorized_key() {
        let data = user_data(
            &mounts(),
            "/projects/parser",
            &plan(),
            None,
            None,
            true,
            &identity_for(SshUser::Hegn),
        );
        assert!(data.contains("PermitRootLogin no"), "{data}");
        assert!(
            !data.contains("PermitRootLogin prohibit-password"),
            "{data}"
        );
        assert!(data.contains("AllowUsers hegn"), "{data}");
        assert!(
            data.contains(
                "  - path: /etc/ssh/authorized_keys/hegn\n    permissions: '0600'\n    owner: root:root\n    content: |\n      ssh-ed25519 "
            ),
            "{data}"
        );
        assert!(
            data.contains("rm -f /etc/ssh/authorized_keys/root /etc/ssh/authorized_keys/ubuntu"),
            "stale keys of the other accounts must be removed: {data}"
        );
        assert!(
            !data.contains("rm -f /etc/ssh/authorized_keys/hegn"),
            "{data}"
        );
        assert!(
            data.contains("install -d -m 0755 -o root -g root /etc/ssh/authorized_keys"),
            "{data}"
        );
        assert!(
            data.contains(
                "chown root:root /etc/ssh/authorized_keys/hegn && chmod 0600 /etc/ssh/authorized_keys/hegn"
            ),
            "{data}"
        );

        let ubuntu = user_data(
            &mounts(),
            "/projects/parser",
            &plan(),
            None,
            None,
            false,
            &identity_for(SshUser::Ubuntu),
        );
        assert!(ubuntu.contains("AllowUsers ubuntu"), "{ubuntu}");
        assert!(ubuntu.contains("PermitRootLogin no"), "{ubuntu}");
        assert!(
            ubuntu.contains("rm -f /etc/ssh/authorized_keys/root /etc/ssh/authorized_keys/hegn"),
            "{ubuntu}"
        );
    }

