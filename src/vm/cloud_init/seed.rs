/// 4 MiB is enough for the seed and keeps it cheap.
const SEED_BYTES: u64 = 4 * 1024 * 1024;

/// Increment when the seed's user-data changes so existing VMs re-run
/// cloud-init on their next boot. Version 13 added the per-VM SSH user, the
/// authorized key, host-key rotation and the guest identity files.
pub const SEED_VERSION: u32 = 13;

/// Guest identity rendered into the cloud-init seed.
///
/// `workspace` is the host path of the primary project; it is shown in the
/// MOTD and exported as `HEGN_WORKSPACE`, never used as a mount path.
#[derive(Debug, Clone, Copy)]
pub struct SeedIdentity<'a> {
    pub vm: &'a str,
    pub project: &'a str,
    pub workspace: &'a str,
    pub ssh_user: SshUser,
    pub ssh_public_key: &'a str,
}

/// One exported project mounted by cloud-init.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MountSpec {
    /// virtio-fs device tag (`hegn-prj-<index>`).
    pub tag: String,
    /// Absolute guest path below `guest_projects_base`.
    pub guest_path: String,
    pub read_only: bool,
}

/// Reject values that could break out of the cloud-init shell command.
pub(crate) fn safe_token(value: &str) -> bool {
    !value.is_empty()
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
}

pub(crate) fn safe_mount(value: &str) -> bool {
    value.starts_with('/')
        && value.len() > 1
        && !value.ends_with('/')
        && !value.contains("//")
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '/' | '-' | '_' | '.'))
        && value
            .split('/')
            .skip(1)
            .all(|segment| !segment.is_empty() && segment != "." && segment != "..")
}

/// Accept exactly one `ssh-ed25519` line without shell or YAML metacharacters.
///
/// The key is generated by [`crate::session::ssh::SshIdentity`], so its
/// alphabet is narrow: base64 material plus a `hegn:<vm>` comment.
pub(crate) fn valid_public_key(key: &str) -> bool {
    if key.is_empty()
        || key != key.trim()
        || key.contains(['\n', '\r', '\t'])
        || key.lines().count() != 1
    {
        return false;
    }
    let Some(rest) = key.strip_prefix("ssh-ed25519 ") else {
        return false;
    };
    if rest.trim().is_empty() {
        return false;
    }
    key.chars().all(|c| {
        c.is_ascii_alphanumeric() || matches!(c, '+' | '/' | '=' | ':' | '.' | '_' | '-' | ' ')
    })
}

fn validate_identity(identity: &SeedIdentity<'_>) -> Result<()> {
    if !safe_token(identity.vm) {
        anyhow::bail!(
            "unsafe VM name for the cloud-init identity: {:?}",
            identity.vm
        );
    }
    validate_identity_text("project", identity.project)?;
    validate_identity_text("workspace", identity.workspace)?;
    if !valid_public_key(identity.ssh_public_key) {
        anyhow::bail!("unsafe SSH public key for the cloud-init seed");
    }
    Ok(())
}

fn validate_identity_text(label: &str, value: &str) -> Result<()> {
    if value.is_empty() || value.trim() != value {
        anyhow::bail!(
            "{label} for the cloud-init identity must be a non-empty single line without \
             leading or trailing whitespace"
        );
    }
    if value.len() > 4096 {
        anyhow::bail!("{label} for the cloud-init identity is too long");
    }
    if value.chars().any(char::is_control) {
        anyhow::bail!("{label} for the cloud-init identity must not contain control characters");
    }
    Ok(())
}

/// Write (or replace) the NoCloud seed at `path`.
///
/// The image is created with mode `0600` and `O_NOFOLLOW`; a planted symlink
/// cannot redirect the write. Every mount is validated before the file is
/// touched.
#[allow(clippy::too_many_arguments)]
pub fn write_seed(
    path: &Path,
    mounts: &[MountSpec],
    primary_guest: &str,
    instance_id: &str,
    provision: &ProvisionPlan,
    profile: Option<&ProfileShare>,
    network: Option<&NetworkLease>,
    endpoints: &[LocalEndpoint],
    credential_hardening: bool,
    identity: &SeedIdentity<'_>,
) -> Result<()> {
    if mounts.is_empty() {
        anyhow::bail!("cloud-init seed needs at least one project mount");
    }
    validate_identity(identity)?;
    for mount in mounts {
        if !safe_token(&mount.tag) {
            anyhow::bail!(
                "unsafe virtio-fs tag for the cloud-init seed: {tag:?}",
                tag = mount.tag
            );
        }
        if !safe_mount(&mount.guest_path) {
            anyhow::bail!(
                "unsafe guest mount path for the cloud-init seed: {path:?}",
                path = mount.guest_path
            );
        }
    }
    if !safe_mount(primary_guest) {
        anyhow::bail!("unsafe primary guest path for the cloud-init seed: {primary_guest:?}");
    }
    if !mounts.iter().any(|mount| mount.guest_path == primary_guest) {
        anyhow::bail!("primary guest path {primary_guest:?} is not one of the mounted projects");
    }
    if !safe_token(instance_id) {
        anyhow::bail!("unsafe cloud-init instance id: {instance_id:?}");
    }
    let endpoint_env = network
        .and_then(|lease| lease.data.as_ref())
        .filter(|_| !endpoints.is_empty())
        .map(|data| endpoint_env(data, endpoints));
    let user_data = super::user_data::user_data_with_id(
        mounts,
        primary_guest,
        provision,
        profile,
        endpoint_env.as_deref(),
        credential_hardening,
        instance_id,
        identity,
    );
    let mut file = OpenOptions::new()
        .create(true)
        .truncate(true)
        .read(true)
        .write(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path)
        .with_context(|| format!("failed to create cloud-init seed {}", path.display()))?;
    // An existing seed may predate the private-file invariant. Tighten it on
    // the open descriptor, so a concurrently replaced path cannot redirect it.
    file.set_permissions(std::fs::Permissions::from_mode(0o600))
        .with_context(|| format!("failed to secure cloud-init seed {}", path.display()))?;
    file.set_len(SEED_BYTES)
        .with_context(|| format!("failed to size cloud-init seed {}", path.display()))?;
    file.seek(SeekFrom::Start(0))?;

    fatfs::format_volume(
        &mut file,
        FormatVolumeOptions::new().volume_label(*b"CIDATA     "),
    )
    .with_context(|| format!("failed to format cloud-init seed {}", path.display()))?;

    {
        let fs = FileSystem::new(&mut file, FsOptions::new())
            .with_context(|| format!("failed to open cloud-init seed {}", path.display()))?;
        let root = fs.root_dir();
        write_file(&root, "user-data", &user_data)?;
        write_file(&root, "meta-data", &meta_data(instance_id, identity.vm))?;
        if let Some(network) = network {
            // The control NIC always exists, so network-config is always
            // present when a lease was reserved (including off mode).
            write_file(&root, "network-config", &network_config(network))?;
        }
    }
    file.sync_all()?;
    Ok(())
}

fn write_file<IO: std::io::Read + std::io::Write + std::io::Seek>(
    root: &fatfs::Dir<'_, IO>,
    name: &str,
    contents: &str,
) -> Result<()> {
    let mut file = root
        .create_file(name)
        .with_context(|| format!("failed to create {name} in the cloud-init seed"))?;
    file.write_all(contents.as_bytes())
        .with_context(|| format!("failed to write {name} in the cloud-init seed"))?;
    file.flush()?;
    Ok(())
}

/// Stable id for this seed. It changes when the seed version, membership,
/// preset, SSH identity, project/workspace identity or network configuration
/// changes, which makes cloud-init re-apply the new user-data/network-config
/// even when the rootfs is reused.
#[allow(clippy::too_many_arguments)]
pub fn instance_id(
    mounts: &[MountSpec],
    primary_guest: &str,
    provision: &ProvisionPlan,
    profile: Option<&ProfileShare>,
    network: Option<&NetworkLease>,
    endpoints: &[LocalEndpoint],
    credential_hardening: bool,
    identity: &SeedIdentity<'_>,
) -> String {
    instance_id_with_generation(
        mounts,
        primary_guest,
        provision,
        profile,
        network,
        endpoints,
        credential_hardening,
        identity,
        0,
    )
}

/// Like [`instance_id`], but binds the seed to a per-VM generation.
///
/// `hegn vm apply` increments the generation so cloud-init re-runs even when
/// every other input is unchanged; that is what rotates the guest host keys.
#[allow(clippy::too_many_arguments)]
pub fn instance_id_with_generation(
    mounts: &[MountSpec],
    primary_guest: &str,
    provision: &ProvisionPlan,
    profile: Option<&ProfileShare>,
    network: Option<&NetworkLease>,
    endpoints: &[LocalEndpoint],
    credential_hardening: bool,
    identity: &SeedIdentity<'_>,
    seed_generation: u64,
) -> String {
    use sha2::{Digest, Sha256};

    debug_assert!(validate_identity(identity).is_ok());
    let mut hasher = Sha256::new();
    hasher.update(SEED_VERSION.to_le_bytes());
    hasher.update(seed_generation.to_le_bytes());
    hasher.update([credential_hardening as u8]);
    hasher.update(identity.vm.as_bytes());
    hasher.update(identity.project.as_bytes());
    hasher.update(identity.workspace.as_bytes());
    hasher.update(identity.ssh_user.as_str().as_bytes());
    hasher.update(identity.ssh_public_key.as_bytes());
    hasher.update(primary_guest.as_bytes());
    for mount in mounts {
        hasher.update(mount.tag.as_bytes());
        hasher.update(mount.guest_path.as_bytes());
        hasher.update([mount.read_only as u8]);
    }
    hasher.update(provision.harness.label().as_bytes());
    hasher.update(provision.script().as_bytes());
    if let Some(profile) = profile {
        hasher.update(profile.manifest_id.as_bytes());
    }
    if let Some(lease) = network {
        // The control configuration is part of every seed; a slot or MAC
        // change must make cloud-init re-apply the new netplan.
        hasher.update(lease.control.control_network_config().as_bytes());
        if let Some(data) = &lease.data {
            hasher.update(data.guest_network_config().as_bytes());
            hasher.update(endpoint_env(data, endpoints).as_bytes());
        }
    }
    let digest = hex::encode(hasher.finalize());
    format!("hegn-{}-v{SEED_VERSION}-{}", identity.vm, &digest[..12])
}

/// The exact `--disk` value for the seed.
pub fn disk_arg(path: &Path) -> String {
    format!("path={},image_type=raw", path.display())
}

