//! Guest endpoint environment derived from the network lease.
//!
//! Local endpoints are reachable from the guest through the host side of the
//! per-instance network, so the generated shell snippet exports the same
//! variables for every login shell.

use crate::config::LocalEndpoint;
use crate::network::Lease;

/// Shell snippet exported to login shells inside the guest.
///
/// `OLLAMA_HOST` is set as a convenience alias; every endpoint is also
/// available as `HEGN_ENDPOINT_<NAME>` for tools without a dedicated variable.
pub(super) fn endpoint_env(lease: &Lease, endpoints: &[LocalEndpoint]) -> String {
    let mut lines = String::from("# Generated by hegn; do not edit.\n");
    for endpoint in endpoints {
        let url = endpoint.url(lease.host_ip);
        lines.push_str(&format!("export {}=\"{url}\"\n", endpoint.env_name()));
        if endpoint.name.eq_ignore_ascii_case("ollama") {
            lines.push_str(&format!("export OLLAMA_HOST=\"{url}\"\n"));
        }
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::network::{Lease, guest_ip, host_ip, mac, tap_name};
    use std::net::Ipv4Addr;

    fn lease() -> Lease {
        Lease {
            index: 0,
            instance: "demo".into(),
            tap: tap_name(0),
            mac: mac(0),
            host_ip: host_ip(0),
            guest_ip: guest_ip(0),
        }
    }

    #[test]
    fn exports_every_endpoint_on_the_tap_host_address() {
        let endpoints = vec![
            LocalEndpoint {
                name: "ollama".into(),
                port: 11434,
            },
            LocalEndpoint {
                name: "llm-local".into(),
                port: 1234,
            },
        ];
        let env = endpoint_env(&lease(), &endpoints);
        assert_eq!(
            env,
            "# Generated by hegn; do not edit.\n\
             export HEGN_ENDPOINT_OLLAMA=\"http://10.213.0.1:11434\"\n\
             export OLLAMA_HOST=\"http://10.213.0.1:11434\"\n\
             export HEGN_ENDPOINT_LLM_LOCAL=\"http://10.213.0.1:1234\"\n"
        );
    }

    #[test]
    fn the_ollama_alias_is_case_insensitive_and_unique() {
        let endpoints = vec![
            LocalEndpoint {
                name: "Ollama".into(),
                port: 11434,
            },
            LocalEndpoint {
                name: "other".into(),
                port: 8080,
            },
        ];
        let env = endpoint_env(&lease(), &endpoints);
        assert_eq!(env.matches("OLLAMA_HOST").count(), 1);
        assert!(env.contains("HEGN_ENDPOINT_OLLAMA="));
        assert!(!env.contains("OLLAMA_HOST=\"http://10.213.0.1:8080\""));
    }

    #[test]
    fn endpoint_names_cannot_inject_shell_syntax() {
        let endpoints = vec![LocalEndpoint {
            name: "evil\";reboot;$(id)".into(),
            port: 11434,
        }];
        let env = endpoint_env(&lease(), &endpoints);
        for line in env.lines().filter(|line| line.starts_with("export ")) {
            assert!(!line.contains(';'), "{line}");
            assert!(!line.contains('$'), "{line}");
        }
        for line in env.lines() {
            assert!(
                line.is_empty() || line.starts_with("# ") || line.starts_with("export "),
                "unexpected shell line: {line:?}"
            );
        }
        let name = endpoints[0].env_name();
        assert!(
            name.chars()
                .all(|ch| ch.is_ascii_alphanumeric() || ch == '_'),
            "{name}"
        );
        assert!(env.contains(&format!("export {name}=\"http://")));
    }

    #[test]
    fn no_endpoints_yields_only_the_header() {
        let env = endpoint_env(&lease(), &[]);
        assert_eq!(env, "# Generated by hegn; do not edit.\n");
        assert_eq!(
            endpoint_env(
                &Lease {
                    host_ip: Ipv4Addr::new(10, 0, 0, 1),
                    ..lease()
                },
                &[]
            ),
            env
        );
    }
}
